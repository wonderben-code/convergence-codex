#!/usr/bin/env python3
"""R13 — the sigma field (The Refined Gaps v2, §A8). Part A: algebra on the Tree's chiral 16.

Pre-registered: "The Tree's Pati-Salam finite geometry, with a Majorana entry in its finite Dirac operator,
yields a scalar singlet sigma ... Refutes: no Majorana entry or no singlet on the Tree's algebra."

The Tree's 16 (PatiSalamOnSixteen / Su2ModuleSixteen): a left block C4 (x) C2 = (4,2,1) and a right block
C4 (x) C2 = (4bar,1,2). su(4) acts as X (x) 1 on the left and -X^T (x) 1 on the right; su(2)_L as 1 (x) A on
the left; su(2)_R as 1 (x) B on the right. Colour index 3 is the lepton (L13: 4 = 3 + 1).
Standard-Model subalgebra: su(3) (the 3x3 block), su(2)_L, and Y = T3R + (B-L)/2 with B-L = diag(1/3,1/3,1/3,-1).

A Majorana entry is a symmetric bilinear psi^T M psi on the 16; a generator G acts by M -> G^T M + M G.
Part A computes, in exact rational arithmetic:
  (1) the Pati-Salam-invariant symmetric M (a constant Majorana entry of a PS-covariant D);
  (2) the Standard-Model-invariant symmetric M;
  (3) the Pati-Salam representation generated by (2): its dimension and Casimirs.
Run: python3 -I scripts/chain_theory/r13_sigma_field.py
"""
import itertools
import sympy as sp

R = sp.Rational
I = sp.I


def kron(a, b):
    return sp.kronecker_product(a, b)


def blockdiag(a, b):
    return sp.diag(a, b)


Z4, Z2, Z8 = sp.zeros(4), sp.zeros(2), sp.zeros(8)
I4, I2 = sp.eye(4), sp.eye(2)


def E(n, i, j):
    m = sp.zeros(n)
    m[i, j] = 1
    return m


# a basis of sl(4) (complexified su(4)): E_ij (i != j) and H_k = E_kk - E_k+1,k+1
sl4 = [E(4, i, j) for i in range(4) for j in range(4) if i != j] + [E(4, k, k) - E(4, k + 1, k + 1) for k in range(3)]
sl3 = [E(4, i, j) for i in range(3) for j in range(3) if i != j] + [E(4, k, k) - E(4, k + 1, k + 1) for k in range(2)]
sl2 = [E(2, 0, 1), E(2, 1, 0), E(2, 0, 0) - E(2, 1, 1)]


def su4_on16(X):
    return blockdiag(kron(X, I2), kron(-X.T, I2))


def su2L_on16(A):
    return blockdiag(kron(I4, A), Z8)


def su2R_on16(B):
    return blockdiag(Z8, kron(I4, B))


BL = sp.diag(R(1, 3), R(1, 3), R(1, 3), -1)
T3R = su2R_on16(sp.diag(R(1, 2), R(-1, 2)))
Y = su4_on16(BL / 2) + T3R

PS = [su4_on16(X) for X in sl4] + [su2L_on16(A) for A in sl2] + [su2R_on16(B) for B in sl2]
SM = [su4_on16(X) for X in sl3] + [su2L_on16(A) for A in sl2] + [Y]

# symmetric 16x16 M with 136 unknowns
syms = sp.symbols("m0:136")
M = sp.zeros(16)
k = 0
for i in range(16):
    for j in range(i, 16):
        M[i, j] = M[j, i] = syms[k]
        k += 1


def invariants(gens):
    eqs = []
    for G in gens:
        D = G.T * M + M * G
        eqs += [D[i, j] for i in range(16) for j in range(i, 16) if D[i, j] != 0]
    A, _ = sp.linear_eq_to_matrix(eqs, syms)
    ns = A.nullspace()
    out = []
    for v in ns:
        Mv = M.subs(dict(zip(syms, v)))
        out.append(Mv)
    return out


ps_inv = invariants(PS)
sm_inv = invariants(SM)
print("PART A — Majorana entries on the Tree's chiral 16 (exact arithmetic)")
print(f"  (1) Pati-Salam-invariant symmetric Majorana matrices: dimension {len(ps_inv)}")
print(f"  (2) Standard-Model-invariant symmetric Majorana matrices: dimension {len(sm_inv)}")

labels = [("L", c, a) for c in range(4) for a in range(2)] + [("R", c, b) for c in range(4) for b in range(2)]
for Mv in sm_inv:
    nz = [(labels[i], labels[j], Mv[i, j]) for i in range(16) for j in range(i, 16) if Mv[i, j] != 0]
    print("      its nonzero entries:", nz)
    (blk, c, b), _, _ = nz[0]
    i0 = labels.index((blk, c, b))
    print(f"      the state: block {blk}, colour index {c} ({'lepton' if c == 3 else 'quark'}), "
          f"T3R = {T3R[i0, i0]}, Y = {Y[i0, i0]}, B-L = {2 * (Y[i0, i0] - T3R[i0, i0])}: the conjugate of nu_R (B-L = -1), so this is nu_R nu_R")

# (3) the PS module generated by the SM-invariant direction
def act(G, Mv):
    return G.T * Mv + Mv * G


def vec(Mv):
    return sp.Matrix([Mv[i, j] for i in range(16) for j in range(i, 16)])


span = [sm_inv[0]]
basis = sp.Matrix.hstack(vec(sm_inv[0]))
frontier = [sm_inv[0]]
while frontier:
    new = []
    for Mv in frontier:
        for G in PS:
            W = act(G, Mv)
            if W == sp.zeros(16):
                continue
            cand = sp.Matrix.hstack(basis, vec(W))
            if cand.rank() > basis.rank():
                basis = cand
                span.append(W)
                new.append(W)
    frontier = new
print(f"  (3) the Pati-Salam module generated by it has dimension {basis.shape[1]}")

# Casimirs on that module: build the action matrices in the module basis
Bm = basis
pinv = (Bm.T * Bm).inv() * Bm.T


def rep_matrix(G):
    cols = [pinv * vec(act(G, Mv)) for Mv in span]
    return sp.Matrix.hstack(*cols)


# su(2)_R Casimir: T3^2 + (T+T- + T-T+)/2 with T+ = E01, T- = E10, T3 = diag(1/2,-1/2)
Tp, Tm, T3 = (rep_matrix(su2R_on16(m)) for m in (E(2, 0, 1), E(2, 1, 0), sp.diag(R(1, 2), R(-1, 2))))
cas_R = sp.simplify(T3 * T3 + (Tp * Tm + Tm * Tp) / 2)
print(f"      su(2)_R Casimir on it: {set(cas_R.diagonal())} with off-diagonal zero: {cas_R.is_diagonal()}  (j(j+1) = 2: a triplet)")
# su(4) Casimir with Tr(T_a T_b) = 1/2 delta in the fundamental: C = sum_{i!=j} E_ij E_ji / 2 + Cartan part
cart = [sp.diag(*[R(1, 2) if t == s else (R(-1, 2) if t == s + 1 else 0) for t in range(4)]) for s in range(3)]
# orthonormalise the Cartan of sl(4) w.r.t. tr(XY): use the explicit form C = (1/2) sum_{i,j} E_ij E_ji - (1/8) (sum_i E_ii)^2
Ms = {(i, j): rep_matrix(su4_on16(E(4, i, j))) for i in range(4) for j in range(4)}
C4 = sum((Ms[(i, j)] * Ms[(j, i)] for i in range(4) for j in range(4)), sp.zeros(basis.shape[1])) / 2
Ntot = sum((Ms[(i, i)] for i in range(4)), sp.zeros(basis.shape[1]))
C4 = sp.simplify(C4 - Ntot * Ntot / 8)
print(f"      su(4) Casimir on it: {set(C4.diagonal())}, diagonal: {C4.is_diagonal()}  "
      f"(fundamental 15/8, the 6: 5/2, the 10: 9/2)")
print("  So the unique Standard-Model-singlet Majorana direction lies in an irreducible 30 = (10bar, 1, 3) of")
print("  Pati-Salam, and no Pati-Salam-invariant Majorana entry exists: a Pati-Salam-covariant Dirac operator")
print("  can carry the Majorana term only as a FIELD in (10bar,1,3), whose Standard-Model-singlet component is sigma.")
